-- Počáteční struktura databáze podle ER diagramu v database/README.md

-- Odstranění diakritiky pro fulltextové vyhledávání (unaccent je trusted extension,
-- role flyway ji smí vytvořit díky právu CREATE na databázi)
create extension if not exists "unaccent";

-- unaccent() není immutable, proto ji nelze přímo použít ve vygenerovaném sloupci ani indexu
create function "immutable_unaccent" ( text ) returns text
    language sql
    immutable parallel safe strict
    return public.unaccent('public.unaccent'::regdictionary, $1);

-- Uživatelé (ID převzato z Keycloaku)
create table "users" (
    "id"         uuid not null,
    "email"      text not null,
    "name"       text not null,
    "is_blocked" boolean not null default false,
    primary key ( "id" )
);

-- Železniční síť
create table "railway_nodes" (
    "id"        uuid not null,
    "latitude"  double precision not null,
    "longitude" double precision not null,
    primary key ( "id" )
);

create table "railway_graph" (
    "node_a_id" uuid not null,
    "node_b_id" uuid not null,
    "distance"  integer not null, -- vzdálenost mezi body v m
    primary key ( "node_a_id", "node_b_id" ),
    foreign key ( "node_a_id" ) references "railway_nodes" ( "id" ),
    foreign key ( "node_b_id" ) references "railway_nodes" ( "id" ),
    check ( "node_a_id" <> "node_b_id" ),
    check ( "distance" >= 0 )
);

-- Stanice je uzel železniční sítě (sdílí jeho ID)
create table "stations" (
    "id"            uuid not null,
    "name"          text not null,
    "search_vector" tsvector generated always as ( to_tsvector('simple', "immutable_unaccent"("name")) ) stored, -- název bez diakritiky pro fulltext
    primary key ( "id" ),
    foreign key ( "id" ) references "railway_nodes" ( "id" ),
    unique ( "name" )
);

create index on "stations" using gin ( "search_vector" );

-- Číselníky
create table "cargo_types" (
    "id"   bigint generated by default as identity,
    "name" text not null,
    primary key ( "id" ),
    unique ( "name" )
);

create table "wagons" (
    "id"                  bigint generated by default as identity,
    "name"                text not null,
    "tare_weight"         double precision not null, -- t
    "net_capacity_weight" double precision not null, -- t
    "gross_weight_limit"  double precision not null, -- t
    "volume_capacity"     double precision not null, -- m3
    "rent_price"          double precision not null, -- Kč/km
    primary key ( "id" )
);

create table "locomotives" (
    "id"                bigint generated by default as identity,
    "name"              text not null,
    "max_towing_weight" double precision not null, -- t
    "max_speed"         double precision not null, -- km/h
    primary key ( "id" )
);

-- Vlakové soupravy
create table "train_sets" (
    "id"              uuid not null,
    "locomotive_id"   bigint not null,
    "station_from"    uuid not null,
    "station_to"      uuid not null,
    "code"            text not null,
    "departure_date"  timestamp with time zone not null,
    "arrival_date"    timestamp with time zone not null,
    "expiration_date" timestamp with time zone not null,
    primary key ( "id" ),
    foreign key ( "locomotive_id" ) references "locomotives" ( "id" ),
    foreign key ( "station_from" ) references "stations" ( "id" ),
    foreign key ( "station_to" ) references "stations" ( "id" ),
    unique ( "code" )
);

create index on "train_sets" ( "locomotive_id" );
create index on "train_sets" ( "station_from" );
create index on "train_sets" ( "station_to" );

-- Objednávky
create table "orders" (
    "id"                  uuid not null,
    "user_id"             uuid not null,
    "train_set_id"        uuid,
    "name"                text not null,
    "status"              text not null,
    "code"                text not null,
    "total_price"         numeric(12, 2) not null, -- Kč
    "load_date"           timestamp with time zone not null,
    "unload_date"         timestamp with time zone not null,
    "preferred_departure" timestamp with time zone not null,
    "preferred_arrival"   timestamp with time zone not null,
    primary key ( "id" ),
    foreign key ( "user_id" ) references "users" ( "id" ),
    foreign key ( "train_set_id" ) references "train_sets" ( "id" ) on delete set null
);

create index on "orders" ( "user_id" );
create index on "orders" ( "train_set_id" );

create table "order_cargoes" (
    "id"            uuid not null,
    "order_id"      uuid not null,
    "cargo_type_id" bigint not null,
    "volume"        double precision not null, -- m3
    "weight"        double precision not null, -- t
    "wagon_id"      bigint not null,
    "wagon_count"   integer not null,
    primary key ( "id" ),
    foreign key ( "order_id" ) references "orders" ( "id" ) on delete cascade,
    foreign key ( "cargo_type_id" ) references "cargo_types" ( "id" ),
    foreign key ( "wagon_id" ) references "wagons" ( "id" ),
    unique ( "order_id" ),
    check ( "wagon_count" > 0 )
);

create index on "order_cargoes" ( "order_id" );
create index on "order_cargoes" ( "cargo_type_id" );
create index on "order_cargoes" ( "wagon_id" );

-- Každá objednávka má právě jednu trasu
create table "order_routes" (
    "id"           uuid not null,
    "order_id"     uuid not null,
    "station_from" uuid not null,
    "station_to"   uuid not null,
    "route"        uuid[] not null, -- sled uzlů (railway_nodes) trasy
    primary key ( "id" ),
    foreign key ( "order_id" ) references "orders" ( "id" ) on delete cascade,
    foreign key ( "station_from" ) references "stations" ( "id" ),
    foreign key ( "station_to" ) references "stations" ( "id" ),
    unique ( "order_id" )
);

create index on "order_routes" ( "station_from" );
create index on "order_routes" ( "station_to" );

create table "order_status_history" (
    "id"         uuid not null,
    "order_id"   uuid not null,
    "status"     text not null,
    "changed_at" timestamp with time zone not null default now(),
    primary key ( "id" ),
    foreign key ( "order_id" ) references "orders" ( "id" ) on delete cascade
);

create index on "order_status_history" ( "order_id", "changed_at" );
